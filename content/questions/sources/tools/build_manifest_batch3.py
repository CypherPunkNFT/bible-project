#!/usr/bin/env python3
"""Measure the batch-3 question books and append them to MANIFEST.md and manifest.json.

Batches 1 and 2 are carried through untouched: this script finds its own marker in
MANIFEST.md and rewrites only what comes after it, and in manifest.json it refuses
to run if merging would alter an entry it does not own.

Per-book provenance is read from the Internet Archive metadata record saved beside
each book's files when it was downloaded, so the manifest cannot drift from what was
actually fetched.

Run: python tools/build_manifest_batch3.py
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

from normalize_batch3 import LICENCE as BATCH_3_LICENCE
from source_metadata_batch3 import BATCH_3, RETRIEVED, JOB

CORPUS_ROOT = Path(__file__).resolve().parent.parent
RAW = CORPUS_ROOT / "raw"
EXTRACTED = CORPUS_ROOT / "extracted"
NORMALIZED = CORPUS_ROOT / "normalized"
MANIFEST_JSON = CORPUS_ROOT / "manifest.json"
MANIFEST_MD = CORPUS_ROOT / "MANIFEST.md"

LINK_BASE = "Jarvis/Projects/BibleProject/Website/content/questions/sources"
BATCH_3_MARKER = "<!-- BATCH 3 BEGINS - generated by tools/build_manifest_batch3.py -->"
SAMPLE_COUNT = 5


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def file_inventory(source_id: str) -> list[dict]:
    root = RAW / source_id
    if not root.is_dir():
        raise RuntimeError(f"no raw folder for source {source_id!r} at {root}")
    return [
        {
            "path": path.relative_to(root).as_posix(),
            "bytes": path.stat().st_size,
            "sha256": sha256(path),
        }
        for path in sorted(p for p in root.rglob("*") if p.is_file())
    ]


def archive_provenance(identifier: str) -> dict:
    """The publication facts, read back out of the saved Internet Archive record."""
    record = json.loads(
        (RAW / "internet-archive-sunday-school-question-books" / identifier
         / f"{identifier}-ia-metadata.json").read_text(encoding="utf-8")
    )
    meta = record.get("metadata", {})
    creator = meta.get("creator")
    if isinstance(creator, list):
        creator = "; ".join(creator)
    return {
        "identifier": identifier,
        "title": meta.get("title"),
        "creator": creator,
        "publisher": meta.get("publisher"),
        "date": meta.get("date") or meta.get("year"),
        "language": meta.get("language"),
        "copyright_statement": meta.get("possible-copyright-status"),
        "scanning_sponsor": meta.get("sponsor") or meta.get("contributor"),
        "item_url": f"https://archive.org/details/{identifier}",
    }


def banks_for(source_id: str) -> list[dict]:
    document = json.loads((EXTRACTED / f"{source_id}.json").read_text(encoding="utf-8"))
    banks = []
    for bank in document["banks"]:
        summary = {
            key: bank[key] for key in bank if key != "questions"
        }
        if source_id == "internet-archive-sunday-school-question-books":
            summary["provenance"] = archive_provenance(bank["bank_id"])
        banks.append(summary)
    return banks


def samples(source_id: str, count: int = SAMPLE_COUNT) -> list[dict]:
    questions = json.loads(
        (NORMALIZED / f"{source_id}.json").read_text(encoding="utf-8")
    )["questions"]
    if not questions:
        return []
    indexes = sorted({int(len(questions) * k / count) for k in range(count)})
    return [
        {
            "bank_id": questions[i]["bank_id"],
            "question": questions[i]["question"],
            "answer": questions[i]["answer"],
            "reference": questions[i]["reference"],
            "page": questions[i]["page"],
        }
        for i in indexes
    ]


def build_entry(source_id: str, meta: dict) -> dict:
    files = file_inventory(source_id)
    banks = banks_for(source_id)
    questions = sum(b["question_count"] for b in banks)
    normalized = json.loads(
        (NORMALIZED / f"{source_id}.json").read_text(encoding="utf-8")
    )["questions"]
    entry = dict(meta)
    # The licence verdict comes from normalize_batch3.py, the one place it is written,
    # so the manifest and the records can never disagree about it.
    verdict = BATCH_3_LICENCE[source_id]
    entry.update(
        {
            "publishable": verdict["publishable"],
            "publishable_reason": verdict["publishable_reason"],
            "usability": "usable",
            "usability_note": verdict["note"],
            "record_count": questions,
            "question_count": questions,
            "bank_count": len(banks),
            "with_answer": sum(1 for q in normalized if q["answer"]),
            "with_reference": sum(1 for q in normalized if q["reference"]),
            "with_page": sum(1 for q in normalized if q["page"] is not None),
            "banks": banks,
            "downloaded": RETRIEVED,
            "local_path": f"raw/{source_id}/",
            "extracted_path": f"extracted/{source_id}.json",
            "normalized_path": f"normalized/{source_id}.json",
            "file_count": len(files),
            "total_bytes": sum(f["bytes"] for f in files),
            "files": files,
        }
    )
    return entry


def write_manifest_json(entries: dict) -> dict:
    """Merge batch 3 in, refusing to alter anything an earlier batch owns."""
    existing = json.loads(MANIFEST_JSON.read_text(encoding="utf-8"))
    earlier_ids = [s for s in existing["sources"] if s not in entries]
    merged = {source_id: existing["sources"][source_id] for source_id in earlier_ids}
    merged.update(entries)
    for source_id in earlier_ids:
        if merged[source_id] != existing["sources"][source_id]:
            raise RuntimeError(f"would have altered an earlier batch's entry: {source_id}")

    batches = dict(existing.get("batches") or {})
    batches["batch_3"] = {
        "job": JOB,
        "downloaded": RETRIEVED,
        "source_ids": sorted(entries),
    }
    totals = dict(existing.get("question_totals") or {})
    batch_3_total = sum(e["question_count"] for e in entries.values())
    totals.update(
        {
            "batch_3_questions_extracted": batch_3_total,
            "batch_3_publishable": batch_3_total,
            "batch_3_research_only": 0,
            "batch_3_note": (
                "Every batch-3 question comes from a work published before 1929 in the "
                "United States, so all of it is public domain and none of it is held "
                "back on licence grounds. The constraint on the 96,545 questions read "
                "off scans is the quality of the machine-read text, not the terms."
            ),
        }
    )
    document = {
        "name": existing.get("name"),
        "generated": existing.get("generated"),
        "generated_by": existing.get("generated_by"),
        "updated": RETRIEVED,
        "updated_by": f"{JOB}, which added the third batch of 2 sources ("
                      f"75 pre-1929 question books)",
        "purpose": existing.get("purpose"),
        "status": existing.get("status"),
        "publishing_rule": existing.get("publishing_rule"),
        "batches": batches,
        "excluded_on_instruction": existing.get("excluded_on_instruction", []),
        "source_count": len(merged),
        "total_bytes": sum(s["total_bytes"] for s in merged.values()),
        "total_files": sum(s["file_count"] for s in merged.values()),
        "question_totals": totals,
        "sources": merged,
    }
    MANIFEST_JSON.write_text(
        json.dumps(document, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    return document


def markdown_files(files: list[dict], source_id: str) -> str:
    lines = ["| File | Bytes | SHA-256 |", "|---|---:|---|"]
    for entry in files:
        link = f"[{entry['path']}]({LINK_BASE}/raw/{source_id}/{entry['path']})"
        lines.append(f"| {link} | {entry['bytes']:,} | `{entry['sha256']}` |")
    return "\n".join(lines)


def markdown_archive_books(banks: list[dict]) -> str:
    lines = [
        "| Book | Published | Publisher | Questions | Of those, referenced | Shape | "
        "Kept of candidates | Item |",
        "|---|---|---|---:|---:|---|---:|---|",
    ]
    for bank in sorted(banks, key=lambda b: str(b["provenance"]["date"])):
        p = bank["provenance"]
        title = (p["title"] or bank["bank_id"]).replace("|", "/")[:88]
        publisher = (p["publisher"] or "—").replace("|", "/")[:48]
        lines.append(
            f"| {title} | {p['date']} | {publisher} | {bank['question_count']:,} | "
            f"{bank['with_reference']:,} | {bank['style']} | {bank['kept_share']:.0%} | "
            f"[{bank['bank_id']}]({p['item_url']}) |"
        )
    return "\n".join(lines)


def markdown_gutenberg_books(banks: list[dict]) -> str:
    lines = [
        "| Book | Published | Questions | With answer | With reference | Ebook |",
        "|---|---|---:|---:|---:|---|",
    ]
    for bank in banks:
        number = bank["gutenberg_ebook"]
        lines.append(
            f"| {bank['title'].replace('|', '/')} | {bank['published']} | "
            f"{bank['question_count']:,} | {bank['with_answer']:,} | "
            f"{bank['with_reference']:,} | "
            f"[ebook {number}](https://www.gutenberg.org/ebooks/{number}) |"
        )
    return "\n".join(lines)


def markdown_samples(rows: list[dict]) -> str:
    lines = []
    for position, row in enumerate(rows, start=1):
        lines.append(f"{position}. **Q:** {row['question']}")
        if row["answer"]:
            lines.append(f"   **A:** {row['answer'][:300]}")
        tail = []
        if row["reference"]:
            tail.append(f"*reference:* {row['reference']}")
        if row["page"] is not None:
            tail.append(f"*page {row['page']}*")
        tail.append(f"*from* `{row['bank_id']}`")
        lines.append("   " + " · ".join(tail))
    return "\n".join(lines)


def markdown_section(source_id: str, entry: dict, rows: list[dict]) -> str:
    if source_id == "internet-archive-sunday-school-question-books":
        books = markdown_archive_books(entry["banks"])
        books_heading = "The 67 books, oldest first"
    else:
        books = markdown_gutenberg_books(entry["banks"])
        books_heading = "The eight books"
    return f"""
### {entry['title']}

**Local folder:** [raw/{source_id}/]({LINK_BASE}/raw/{source_id}/) · **Publishable** — every
work predates 1929

| Field | Value |
|---|---|
| Source | {entry['source_url']} |
| Kind | {entry['source_kind']} |
| Revision | {entry['revision']} |
| Retrieved | {entry['downloaded']} |
| How | {entry['download_method']} |
| Licence as stated | {entry['licence_as_stated']} |
| Attribution required | {'**Yes**' if entry['attribution_required'] else 'No'} |
| Questions written by | **{entry['questions_written_by']}** |
| Books | {entry['bank_count']} |
| Questions extracted | **{entry['question_count']:,}** |
| …with an answer | {entry['with_answer']:,} |
| …with a scripture reference | {entry['with_reference']:,} |
| …with a printed page number | {entry['with_page']:,} |
| Files / size | {entry['file_count']} files, {entry['total_bytes']:,} bytes |
| In git? | {entry['git']} |

**How copyright was checked.** {entry['copyright_check']}

**Where the licence does not settle it.** {entry['licence_nuance']}

**Format.** {entry['format']}

**Quality note.** {entry['quality_note']}

**Five sampled questions** (evenly spaced through the normalised bank):

{markdown_samples(rows)}

**Extractions:** [extracted/{source_id}.json]({LINK_BASE}/extracted/{source_id}.json) ·
[normalized/{source_id}.json]({LINK_BASE}/normalized/{source_id}.json)

#### {books_heading}

{books}

#### Every file, with its hash

{markdown_files(entry['files'], source_id)}

---
"""


def write_manifest_md(entries: dict, samples_by_source: dict, document: dict) -> None:
    existing = MANIFEST_MD.read_text(encoding="utf-8")
    if BATCH_3_MARKER in existing:
        existing = existing[: existing.index(BATCH_3_MARKER)].rstrip() + "\n"

    ordered = sorted(entries, key=lambda s: -entries[s]["question_count"])
    batch_bytes = sum(e["total_bytes"] for e in entries.values())
    batch_files = sum(e["file_count"] for e in entries.values())
    batch_questions = sum(e["question_count"] for e in entries.values())
    batch_books = sum(e["bank_count"] for e in entries.values())
    with_answer = sum(e["with_answer"] for e in entries.values())
    with_reference = sum(e["with_reference"] for e in entries.values())

    overview = "\n".join(
        f"| [{entries[s]['title']}]({LINK_BASE}/raw/{s}/) | {entries[s]['bank_count']} | "
        f"{entries[s]['question_count']:,} | {entries[s]['with_answer']:,} | "
        f"{entries[s]['with_reference']:,} | {entries[s]['total_bytes']:,} |"
        for s in ordered
    )

    sections = "".join(
        markdown_section(s, entries[s], samples_by_source[s]) for s in ordered
    )

    MANIFEST_MD.write_text(
        existing + HEADER.format(
            marker=BATCH_3_MARKER,
            retrieved=RETRIEVED,
            job=JOB,
            books=batch_books,
            files=batch_files,
            size=batch_bytes,
            questions=batch_questions,
            with_answer=with_answer,
            with_reference=with_reference,
            overview=overview,
            link_base=LINK_BASE,
            corpus_sources=document["source_count"],
            corpus_bytes=document["total_bytes"],
            corpus_files=document["total_files"],
        ) + sections,
        encoding="utf-8",
    )


HEADER = """
{marker}

# Batch 3 — seventy-five pre-1929 Sunday school question books

**Class:** RAW DATA · **Retrieved:** {retrieved} · **State last verified:** {retrieved}
**Added by:** {job}

Everything above this line is batches 1 and 2 and is unchanged. This batch adds **two
sources holding {books} separate books, {files} files, {size:,} bytes**, from which
**{questions:,} questions** were extracted — **{with_answer:,}** of them with the answer
the book printed, and **{with_reference:,}** with a scripture reference.

These are the real thing the corpus was missing: not trivia written for an app, but the
question books American and British Sunday schools actually used, printed between 1692 and
1927 and long out of copyright. They ask chapter-by-chapter comprehension questions on
Scripture — *"Who called to Samuel three times one night?"*, *"What did the Israelites say
respecting the manna?"* — which is what a Bible quiz is made of.

**Every work in this batch was published before 1929, so all of it is in the public domain
in the United States, and none of it is held back on licence grounds.** Since the owner's
publishing rule of 2026-10-17 that is true of batch 2 as well, so this batch is no longer
the exception it was when it was written; what still sets it apart is that nothing here
carries any attribution or share-alike obligation at all. The constraint here is
different and it is real: see the quality notes below.

**The scans are not in git.** The page images come to 773 MB. They stay on disk and this
manifest is the record of them, with a SHA-256 for every file. The extracted and
normalised JSON is small and is committed.

Corpus totals across all three batches: **{corpus_sources} sources, {corpus_files} files,
{corpus_bytes:,} bytes.**

## The two sources at a glance

| Source | Books | Questions | With answer | With reference | Bytes |
|---|---:|---:|---:|---:|---:|
{overview}

## What was looked for, and what was left out

The search covered the Internet Archive and Project Gutenberg for American Sunday School
Union question books, Sunday school lesson quarterlies, catechetical Bible question books
and anything similar carrying chapter-by-chapter or story questions on Scripture. Sixty-one
catalogue queries returned 601 distinct candidates; 75 were kept.

Left out deliberately:

- **General-knowledge question books.** "The question book" was a whole genre of
  nineteenth-century schoolroom cramming — arithmetic, geography, teacher certification.
  Most of what the phrase returns is not about the Bible at all.
- **Doctrinal church catechisms with no scriptural narrative.** The eighteenth-century
  British collection alone holds dozens of printings of John Lewis's *Church Catechism
  Explain'd*. Catechisms are only here where the project did not already have them.
- **Duplicate scans.** Several books are on the Internet Archive three or four times over;
  one copy of each was taken.
- **STEPBible.** The project forbids copying STEP's study tables; nothing was taken from
  there.
- **Quizlet, Scribd and anything login-walled or scraping-forbidden.** No scraping was done
  for this batch. Everything came from a publishing endpoint: the Internet Archive's own
  item-download service and metadata API, and Project Gutenberg's own catalogue and file
  service.
- **Luther's Small Catechism as Project Gutenberg ebook 1670**, which is a 1994
  translation — the work is old but that rendering of it is not, so it fails the pre-1929
  test the rest of the batch passes.

## Three books that are here but yielded nothing

They are kept because the download and its provenance are the record, and because a reader
coming after should not have to rediscover why they are empty:

- **Answers to 1200 Bible Questions in Consecutive Order (1903)** — this is the *answer
  key* on its own. The questions were published separately and are not in it; what it holds
  is a table of scripture references, and the scan of that table is close to unreadable.
- **Short Bible-Study Questions and Answers (1924)** — it is in **Hopi**. It is a genuine
  pre-1929 Sunday school question book, translated by Otto Lomavitu, and the English
  extractor cannot read a word of it.
- **The Teacher's Assistant in the Use of the Fourth Volume of Union Questions (1833)** —
  an American Sunday School Union title, but it is a teacher's exposition rather than a
  question book, with 51 question marks in 491,000 characters, and the scan is badly
  degraded.

## The tools

| Tool | What it does |
|---|---|
| [question_book_ocr.py]({link_base}/tools/question_book_ocr.py) | shared text tidying, page-header detection, scripture-reference parsing and the quality gate |
| [extract_question_books.py]({link_base}/tools/extract_question_books.py) | parses the 67 scanned Internet Archive books |
| [extract_gutenberg_question_books.py]({link_base}/tools/extract_gutenberg_question_books.py) | parses the 8 Project Gutenberg transcriptions, one parser per book |
| [normalize_batch3.py]({link_base}/tools/normalize_batch3.py) | rewrites both extractions into the common format with their licence attached |
| [source_metadata_batch3.py]({link_base}/tools/source_metadata_batch3.py) | the provenance and licence facts for this batch |
| [build_manifest_batch3.py]({link_base}/tools/build_manifest_batch3.py) | measures sizes, hashes and counts and writes this section and `manifest.json` |

Re-run order: the two extractors, then `normalize_batch3.py`, then
`build_manifest_batch3.py`. All of them read `raw/` and never write to it.

---
"""


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    entries, samples_by_source = {}, {}
    for source_id, meta in BATCH_3.items():
        entries[source_id] = build_entry(source_id, meta)
        samples_by_source[source_id] = samples(source_id)
        entry = entries[source_id]
        print(
            f"  {source_id:<46} {entry['question_count']:>7,} questions  "
            f"{entry['bank_count']:>3} books  {entry['file_count']:>4} files  "
            f"{entry['total_bytes']:>12,} bytes",
            flush=True,
        )

    document = write_manifest_json(entries)
    write_manifest_md(entries, samples_by_source, document)
    print(
        f"\n  manifest.json: {document['source_count']} sources, "
        f"{document['total_files']} files, {document['total_bytes']:,} bytes",
        flush=True,
    )
    print(f"  wrote {MANIFEST_MD.name} and {MANIFEST_JSON.name}", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
