def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    entries, samples_by_source = {}, {}
    for source_id, meta in BATCH_2.items():
        entries[source_id] = build_entry(source_id, meta)
        samples_by_source[source_id] = sample_questions(source_id)
        entry = entries[source_id]
        print(
            f"  {source_id:<42} {entry['question_count']:>5} questions  "
            f"{entry['file_count']:>3} files  {entry['total_bytes']:>12,} bytes",
            flush=True,
        )

    document = write_manifest_json(entries)
    write_manifest_md(entries, samples_by_source, document)
    print(
        f"\n  manifest.json: {document['source_count']} sources, "
        f"{document['total_files']} files, {document['total_bytes']:,} bytes",
        flush=True,
    )
    print(f"  question totals: {document['question_totals']}", flush=True)
    print(f"  wrote {MANIFEST_MD.name} and {MANIFEST_JSON.name}", flush=True)


if __name__ == "__main__":
    sys.exit(main())
