import assert from 'node:assert/strict';
import { searchParables } from '../src/pages/study/parables/search';
import { PARABLES } from '../src/data/parables';
const ids=(query:string)=>searchParables(query).map(story=>story.id);
assert.deepEqual(ids('son prodigal'),['sons']);
assert.deepEqual(ids('  PRODiGAL   son  '),['sons']);
assert.deepEqual(ids('neighbor road'),['samaritan']);
assert.deepEqual(ids('neighbour road'),['samaritan']);
assert.ok(ids("father's gifts").includes('father-gifts'));
assert.deepEqual(ids('wheat & weeds'),ids('wheat and weeds'));
assert.deepEqual(ids('Matt. 13:18'),['sower']);
assert.deepEqual(ids('Mt13:18'),['sower']);
assert.ok(ids('Luke 11:33').includes('lamp'));
assert.ok(ids('Matthew 12:35').includes('tree-fruit'));
assert.deepEqual(ids('Luke 1'),[]);
assert.deepEqual(ids('Luke 15'),['sheep','coin','sons']);
assert.deepEqual(ids('Lk 15:7-8'),['sheep','coin']);
assert.deepEqual(ids('Lk 15:8–7'),[]);
assert.deepEqual(ids('Luke 15:0'),[]);
assert.deepEqual(ids('Matthew 999'),[]);
assert.deepEqual(ids('utterly nonexistent phrase'),[]);
assert.ok(ids('forgiveness').length>1);
assert.equal(ids('  ').length,PARABLES.length);
for(const story of PARABLES) assert.ok(ids(story.title).includes(story.id),`Cannot find title: ${story.title}`);
console.log('Parables search: all titles, reordered words, aliases, spelling, punctuation, themes and Bible-range boundaries passed.');
