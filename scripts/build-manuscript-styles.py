"""Generate the Manuscripts page's stylesheet from the approved mock-up's own CSS, so the live page looks exactly like it.

  src/pages/study/manuscripts/mockup-manuscripts.css  from design/authors-directions/shared/frame.css (page pieces only),
                                                      teachers/teachers.css and design/manuscripts-directions/css/ms.css,
                                                      sections.css

Every rule is scoped under the page's root class (.ms-root), so nothing here reaches another page. The mock-up frame's
site chrome (header, footer, palette, fonts) is left out: the site provides its own. The mock-ups' direction switch and
the pieces direction B does not use are set aside. The mock-up's outside-scroll classes (.os-*) are renamed to the site's
OutsideScroll component's. Hand-written additions live in manuscripts.css, never here. Same method as
scripts/build-hymn-styles.py. Re-run after the mock-up's CSS changes:
    py -3.12 scripts/build-manuscript-styles.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
SITE = Path(__file__).resolve().parents[1]
DESIGN = SITE / "design"
TARGET = SITE / "src/pages/study/manuscripts/mockup-manuscripts.css"
ROOT = ".ms-root"

OS_RENAME = [(".os-area", ".outside-scroll-area"), (".os-frame", ".outside-scroll-frame"), (".os-viewport", ".outside-scroll-viewport"),
             (".os-content", ".outside-scroll-content"), (".os-bar", ".outside-scrollbar"), (".os-extent", ".w-px")]
CHROME = re.compile(r"^(html|:root(\[[^\]]*\])?$|main|\.site-header|\.strip|\.bar\b|\.logo|\.nav|\.search-btn|\.theme-switch|\.site-footer|\.foot-|\.chart-link|\.open-chart)")
# The mock-ups' A/B/C/D switch, A's century strip and the old link list, none of which direction B shows.
SET_ASIDE = re.compile(r"^(\.dir-switch|\.cs\b|\.cs-|\.on-grid|\.on-links)")
THEMED = re.compile(r"^(:root\[data-theme=\"(?:dark|light)\"\])\s+(.*)$")


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def blocks(css: str):
    i = 0
    while True:
        start = css.find("{", i)
        if start < 0:
            return
        depth, j = 1, start + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        yield css[i:start].strip(), css[start + 1:j - 1]
        i = j


def split_selectors(prelude: str) -> list[str]:
    """Split on top-level commas only (":is(a, b)" stays whole)."""
    parts, depth, cur = [], 0, ""
    for ch in prelude:
        depth += {"(": 1, ")": -1}.get(ch, 0)
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    return parts + [cur]


def scope_selector(sel: str) -> str | None:
    sel = sel.strip()
    if not sel or CHROME.match(sel) or SET_ASIDE.match(sel):
        return None
    sel = sel.replace(", .dir-switch)", ")")  # the switch inside a :where() list
    for old, new in OS_RENAME:
        sel = sel.replace(old, new)
    themed = THEMED.match(sel)
    if themed:
        return f"{themed.group(1)} {ROOT} {themed.group(2)}"
    if sel == "body":
        return ROOT
    if sel.startswith("body "):
        return f"{ROOT} {sel[5:]}"
    return f"{ROOT} {sel}"


def scope(css: str) -> str:
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith(("@media", "@supports")):
            inner = scope(body)
            if inner.strip():
                out.append(f"{prelude} {{\n{inner}}}\n")
        elif prelude.startswith("@font-face"):
            continue
        elif prelude.startswith("@"):
            out.append(f"{prelude} {{{' '.join(body.split())}}}\n")
        elif prelude == "body" and "100dvh" in body:
            continue  # the frame's sticky-footer layout: page chrome, not the page
        else:
            sels = [s for s in (scope_selector(x) for x in split_selectors(prelude)) if s]
            if sels:
                out.append(f"{', '.join(sels)} {{ {' '.join(body.split())} }}\n")
    return "".join(out)


def main() -> None:
    files = [DESIGN / "authors-directions/shared/frame.css", DESIGN / "authors-directions/teachers/teachers.css",
             DESIGN / "manuscripts-directions/css/ms.css", DESIGN / "manuscripts-directions/css/sections.css"]
    lead = "/* Generated by scripts/build-manuscript-styles.py from the approved mock-up's CSS. Do not edit; hand additions go in manuscripts.css. */\n"
    text = lead + "".join(f"\n/* ── from {f.relative_to(SITE).as_posix()} ── */\n" + scope(strip_comments(f.read_text(encoding="utf-8"))) for f in files)
    bad = [line for line in text.splitlines() if "dir-switch" in line or ".os-" in line or f"{ROOT} :root" in line]
    if bad:
        raise ValueError(f"{TARGET.name}: a set-aside, unrenamed or mis-scoped rule slipped through: {bad[:3]}")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(SITE).as_posix()}: {text.count('{')} rules")


if __name__ == "__main__":
    main()
