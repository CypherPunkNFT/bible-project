import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const cssPath=path.join(root,'src/components/standard-page-motion.css');
// Named page snapshots already used by the existing section controllers.
// Apologetics and in-page Study tab transitions are intentionally not rewritten.
const names=['people-page','topics-page','places-page','teacher-page','resource-page'];
const css=`/* Generated by scripts/standardize-page-transitions.mjs. */
html[data-site-page-slide] #main{view-transition-name:site-page;background:var(--page)}
html[data-site-page-slide] [data-site-header]{view-transition-name:site-header}
html[data-site-page-slide]::view-transition{pointer-events:none}
html[data-site-page-slide]::view-transition-old(root){display:none}
html[data-site-page-slide]::view-transition-new(root),html[data-site-page-slide]::view-transition-group(site-page){animation:none}
html[data-site-page-slide]::view-transition-old(site-page){translate:0 var(--site-old-shift,0px)}
${['site-page',...names].map(name=>`::view-transition-old(${name}){animation:site-page-lift-out 260ms ease both!important;clip-path:none!important;mix-blend-mode:normal;height:auto}
::view-transition-new(${name}){animation:site-page-rise-in 440ms cubic-bezier(.22,1,.36,1) 50ms both!important;clip-path:none!important;mix-blend-mode:normal;height:auto}`).join('\n')}
/* Remove competing card morphs on page routes that now share the standard motion. */
html[data-topics-slide][data-topics-morph] [data-topics-morph],html[data-places-slide][data-places-morph] [data-places-morph]{view-transition-name:none!important}
@keyframes site-page-lift-out{to{opacity:0;transform:translateY(-14px)}}
@keyframes site-page-rise-in{from{opacity:0;transform:translateY(28px)}}
@media(prefers-reduced-motion:reduce){${['site-page',...names].flatMap(name=>['old','new'].map(p=>`::view-transition-${p}(${name})`)).join(',')}{animation:none!important}}
`;
if(process.argv.includes('--check')){
 if(fs.readFileSync(cssPath,'utf8')!==css)throw Error('Run node scripts/standardize-page-transitions.mjs');
 const app=fs.readFileSync(path.join(root,'src/App.tsx'),'utf8');
 if(!app.includes('<PageTransitions>'))throw Error('Shared route transition provider missing');
 const known=new Set([...names,'ap-section-page','site-header','site-page','study-panel','places-ticker']);
 function audit(dir){for(const entry of fs.readdirSync(dir,{withFileTypes:true})){const file=path.join(dir,entry.name);if(entry.isDirectory())audit(file);else if(file.endsWith('.css'))for(const match of fs.readFileSync(file,'utf8').matchAll(/view-transition-name\s*:\s*([\w-]+)\s*[;}]/g)){if(!known.has(match[1])&&!['none','root'].includes(match[1]))throw Error(`Uncovered page snapshot ${match[1]} in ${file}`);}}}
 audit(path.join(root,'src'));console.log('PASS: shared router transition enabled; all named page snapshots covered; Apologetics excluded');
}else{fs.writeFileSync(cssPath,css);console.log('Generated standard motion for shared router and '+names.length+' existing page controllers');}
