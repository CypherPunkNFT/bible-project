#!/usr/bin/env python3
"""Memory card match (the /games/memory-match game): check the hand-kept pairs and write the files the game ships.

Three versions: people and their stories (characters.json, pairs.json), places and what happened there (places.json,
mm_places.py) and the two halves of a well-known verse (verses.json, mm_verses.py), each with its own review sheet.

The who cards and pairs are hand-kept in scripts/memory-match/ (characters.json, pairs.json). This script checks them
against the site's people, the BSB text and the question bank, fails on any rule in the design
(docs/features/memory-match/design.md 4.1 and 5.2), and writes the game's data and a review sheet. No language model is
used, and the game stores verse ids only: the key verse's words are looked up in the browser (src/lib/verses.ts).

    py -3.12 scripts/build-memory-match.py           # write src/data/memory-match/pairs.json and the review sheet
    py -3.12 scripts/build-memory-match.py --check   # fail if either is out of date
"""
import argparse
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
sys.path.insert(0, str(Path(__file__).resolve().parent / "memory-match"))

from mm_build import HERE, SHY, SITE, BuildError, Sources, parse_ref, read_json  # noqa: E402
from mm_pairs import Character, document, load_characters, load_pairs  # noqa: E402
from mm_places import places_document  # noqa: E402
from mm_verses import verses_document  # noqa: E402

OUT_DATA = SITE / "src" / "data" / "memory-match" / "pairs.json"
OUT_SHEET = SITE / "docs" / "features" / "memory-match" / "review-sheet.md"
OUT_PLACES = SITE / "src" / "data" / "memory-match" / "places.json"
OUT_PLACES_SHEET = SITE / "docs" / "features" / "memory-match" / "places-review-sheet.md"
OUT_VERSES = SITE / "src" / "data" / "memory-match" / "verses.json"
OUT_VERSES_SHEET = SITE / "docs" / "features" / "memory-match" / "verses-review-sheet.md"


def write_lines(doc: dict, rows: str = "pairs") -> str:
    """The shipped JSON with one pair per line, so a change shows as a readable diff."""
    head = {k: v for k, v in doc.items() if k != rows}
    text = json.dumps(head, ensure_ascii=False, indent=1)[:-2]
    pairs = ",\n".join("  " + json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in doc[rows])
    return f'{text},\n "{rows}": [\n{pairs}\n ]\n}}\n'


def headings(book: str) -> list[tuple[tuple[int, int], str]]:
    """The BSB section headings of a book in reading order, from the reader text in data/text/bsb/<BOOK>/."""
    out = []
    for path in sorted((SITE / "data" / "text" / "bsb" / book).glob("*.json"), key=lambda p: int(p.stem)):
        for chapter in read_json(path).values():
            for verse in chapter["v"]:
                for kind, text in verse.get("h", []):
                    if kind == "s" and verse["n"].isdigit():
                        out.append(((int(chapter["c"]), int(verse["n"])), text))
    return sorted(out)


def heading_for(ref: str, cache: dict) -> str:
    """The heading at or just before a passage's first verse."""
    first = parse_ref(ref)[0]
    if first.book not in cache:
        cache[first.book] = headings(first.book)
    before = [text for at, text in cache[first.book] if at <= first.start]
    return before[-1] if before else ""


def cell(text: str) -> str:
    return str(text).replace(SHY, "").replace("|", "\\|")


def review_sheet(doc: dict, people: dict[str, Character], raw_pairs: list[dict], decks: list[dict],
                 sources: Sources) -> str:
    characters = doc["characters"]
    cache: dict = {}
    lines = ["# Memory card match: review sheet", "",
             "Generated by `py -3.12 scripts/build-memory-match.py`; do not edit. One row per pair: the BSB heading at or",
             "before the passage (evidence the passage is the story), the key verse shown on the end screen, the tier, the",
             "person's mention count and question-bank count (two fame signals), and the characters it never shares a",
             "board with. Edit `scripts/memory-match/pairs.json` and rebuild.", "",
             "## Pools by deck and difficulty", "",
             "Distinct characters in each pool (a board needs its pair count + 3 to be offered; Hard also needs 4 at tier 2",
             "or 3). A dash means the combination is hidden.", "",
             "| Deck | Pairs | Easy (6) | Medium (9) | Hard (12) | Easy top-up from tier 2 |", "|---|---|---|---|---|---|"]
    for deck in decks:
        pools = deck["_pools"]
        counts = [f"{len({p.who for p in pools[d]})}" + ("" if deck["offered"][d] else " —") for d in ("easy", "medium", "hard")]
        extra = ", ".join(cell(characters[p.who]["label"]) for p in pools["easy"] if p.id in deck["easyExtra"]) or "none"
        lines.append(f"| {deck['title']} | {len(pools['hard'])} | {' | '.join(counts)} | {extra} |")
    lines += ["", "## Pairs", "",
              "| # | Who | Story card | Passage | BSB heading | Key verse | Tier | Mentions | Bank | Never with |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    for n, (pair, raw) in enumerate(zip(doc["pairs"], raw_pairs), start=1):
        character = characters[pair["who"]]
        record = sources.people.get(people[pair["who"]].person or "")
        mentions = record["c"] if record else "—"
        bank = sources.bank_counts.get(record["n"], 0) if record else "—"
        never = ", ".join(cell(characters[k]["label"]) for k in pair["notWith"]) or "—"
        lines.append(f"| {n} | {cell(character['label'])} | {cell(pair['story'])} | {pair['ref']} | "
                     f"{cell(heading_for(raw['ref'], cache))} | {pair['keyVerse']} | {pair['tier']} | {mentions} | "
                     f"{bank} | {never} |")
    return "\n".join(lines) + "\n"


def pools_table(decks: list[dict]) -> list[str]:
    lines = ["| Deck | Easy (6) | Medium (9) | Hard (12) |", "|---|---|---|---|"]
    for deck in decks:
        counts = [f"{len({p.who for p in deck['_pools'][d]})}" + ("" if deck["offered"][d] else " —")
                  for d in ("easy", "medium", "hard")]
        lines.append(f"| {deck['title']} | {' | '.join(counts)} |")
    return lines


def places_sheet(doc: dict, decks: list[dict]) -> str:
    characters = doc["characters"]
    lines = ["# Memory card match, Places: review sheet", "",
             "Generated by `py -3.12 scripts/build-memory-match.py`; do not edit. Edit `scripts/memory-match/places.json`",
             "and rebuild. Every event's passage names its place in the BSB, and the place's atlas record lists a verse",
             "of it. Places per deck and difficulty (a dash: hidden, too few):", "", *pools_table(decks), "",
             "| # | Place | Event | Passage | Key verse | Tier | Never with |", "|---|---|---|---|---|---|---|"]
    for n, pair in enumerate(doc["pairs"], start=1):
        never = ", ".join(cell(characters[k]["label"]) for k in pair["notWith"]) or "—"
        lines.append(f"| {n} | {cell(characters[pair['who']]['label'])} | {cell(pair['story'])} | {pair['ref']} | "
                     f"{pair['keyVerse']} | {pair['tier']} | {never} |")
    return "\n".join(lines) + "\n"


def verses_sheet(decks: list[dict], pairs: list, left_out: list[tuple[str, str]]) -> str:
    """The splits in words, for a person to read. Under docs/, which the verse-wording check does not cover; the
    shipped file holds ids and split points only."""
    refs = {p.id: f"{p.book} {p.chapter}:{p.number}" for p in pairs}
    lines = ["# Memory card match, Verses: review sheet", "",
             "Generated by `py -3.12 scripts/build-memory-match.py`; do not edit. The verses are verse completion's pool;",
             "each splits at the pause nearest its middle. Leave a verse out in `scripts/memory-match/verses.json`.",
             "Verses per deck and difficulty:", "", *pools_table(decks), "",
             "| # | Verse | First card | Second card | Tier | Hard | Never with |", "|---|---|---|---|---|---|---|"]
    for n, p in enumerate(pairs, start=1):
        never = ", ".join(refs[k] for k in sorted(p.not_with)) or "—"
        lines.append(f"| {n} | {refs[p.id]} | {cell(p.first)} … | … {cell(p.second)} | {p.tier} | "
                     f"{'yes' if p.hard else 'no'} | {never} |")
    lines += ["", "## Left out", "", "| Passage | Why |", "|---|---|"]
    lines += [f"| {pid} | {cell(why)} |" for pid, why in left_out]
    return "\n".join(lines) + "\n"


def build() -> dict[Path, str]:
    """Run the whole build in memory and return each output file's text."""
    sources = Sources.load()
    raw_characters = read_json(HERE / "characters.json")["characters"]
    raw_pairs = read_json(HERE / "pairs.json")["pairs"]
    characters = load_characters(raw_characters, sources)
    pairs = load_pairs(raw_pairs)
    doc, decks = document(characters, pairs, sources)
    records = {r["id"]: r for r in read_json(SITE / "data" / "places.json")}
    places_doc, place_decks = places_document(read_json(HERE / "places.json"), sources, records)
    verses_doc, verse_decks, verse_pairs, left_out = verses_document(read_json(HERE / "verses.json"), sources)
    return {OUT_DATA: write_lines(doc), OUT_SHEET: review_sheet(doc, characters, raw_pairs, decks, sources),
            OUT_PLACES: write_lines(places_doc), OUT_PLACES_SHEET: places_sheet(places_doc, place_decks),
            OUT_VERSES: write_lines(verses_doc, "verses"),
            OUT_VERSES_SHEET: verses_sheet(verse_decks, verse_pairs, left_out)}


def stale_outputs(outputs: dict[Path, str]) -> list[Path]:
    """Output files missing or different from a fresh build."""
    return [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed output is out of date")
    args = parser.parse_args()
    try:
        outputs = build()
    except BuildError as error:
        print(f"build-memory-match: {error}", file=sys.stderr)
        return 1
    if args.check:
        stale = stale_outputs(outputs)
        for path in stale:
            print(f"build-memory-match: {path.relative_to(SITE)} is out of date; run py -3.12 scripts/build-memory-match.py",
                  file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    doc = json.loads(outputs[OUT_DATA])
    places = json.loads(outputs[OUT_PLACES])
    verses = json.loads(outputs[OUT_VERSES])
    print(f"build-memory-match: {len(doc['pairs'])} pairs, {len(doc['characters'])} characters; "
          f"{len(places['pairs'])} place events, {len(places['characters'])} places; {len(verses['verses'])} verses")
    for deck in doc["decks"] + places["decks"] + verses["decks"]:
        hidden = [d for d, ok in deck["offered"].items() if not ok]
        print(f"  {deck['title']}: " + (f"hidden at {', '.join(hidden)}" if hidden else "offered at every difficulty"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
