// Timeline sort build: the owner's review sheet (design §4.6), every event's window beside the other sources, every
// fact with its verse, every contested pair and every warning with its resolution, era by era, in plain words.
import { ERAS, type Era, type Tier } from "../../src/pages/games/timeline/order.ts";

export interface SheetEvent {
  id: string; label: string; era: Era; tier: Tier; lo: number | null; hi: number | null; shown: boolean;
  dating: string; anchor: string; theographic?: string; retired?: boolean; dropped?: boolean;
}
export interface SheetFact { first: string; second: string; why: string; refs: string; close: boolean }
export interface SheetWarning { id: string; text: string }

const year = (value: number | null) => (value === null ? "open" : value < 0 ? `${-value} BC` : `AD ${value}`);
const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function reviewSheet(input: {
  events: SheetEvent[]; facts: SheetFact[]; contested: { a: string[]; b: string[]; reason: string }[];
  warnings: SheetWarning[]; resolutions: Record<string, string>; notices: string[]; stamp: string; dailyDays: number; frozenThrough: number;
}): string {
  const label = new Map(input.events.map((event) => [event.id, event.label]));
  const name = (id: string) => label.get(id) ?? id;
  const lines = [
    "# Timeline sort — review sheet",
    "",
    "Generated by `node --experimental-strip-types scripts/build-timeline.ts`; do not edit. The sources are",
    "`src/data/timeline/events.source.json`, `facts.source.json` and `contested.source.json`",
    "([design](design.md), §4.6).",
    "",
    `Stamp ${input.stamp}. ${input.events.length} events, ${input.facts.length} order facts, ${input.contested.length} contested entries. ` +
      `Daily schedule: ${input.dailyDays} puzzles, frozen through #${input.frozenThrough}.`,
    "",
    "## Warnings",
    "",
  ];
  if (!input.warnings.length) lines.push("None.");
  for (const warning of input.warnings) {
    const note = input.resolutions[warning.id];
    lines.push(`- ${warning.text} ${note ? `**Resolved:** ${note}` : "**Needs a resolution note** (`resolutions` in events.source.json)."} \`${warning.id}\``);
  }
  lines.push("", "## Notices", "", ...(input.notices.length ? input.notices.map((notice) => `- ${notice}`) : ["None."]));
  for (const era of ERAS) {
    const events = input.events.filter((event) => event.era === era.key);
    lines.push("", `## ${era.title} (${events.length})`, "", "| Event | Tier | Window | Dating line | How the window was set | Theographic |", "|---|---|---|---|---|---|");
    for (const event of events) {
      const flags = [event.retired ? "retired" : "", event.dropped ? "left out: too few partners" : "", event.shown ? "" : "order only"].filter(Boolean).join(", ");
      lines.push(`| ${cell(event.label)}${flags ? ` *(${flags})*` : ""} | ${event.tier} | ${year(event.lo)} – ${year(event.hi)} | ${cell(event.dating)} | ${cell(event.anchor)} | ${cell(event.theographic ?? "")} |`);
    }
  }
  lines.push("", "## Order facts", "", "| Earlier | Later | Why | Verse | Close |", "|---|---|---|---|---|");
  for (const fact of input.facts) lines.push(`| ${cell(name(fact.first))} | ${cell(name(fact.second))} | ${cell(fact.why)} | ${fact.refs} | ${fact.close ? "yes" : ""} |`);
  lines.push("", "## Never dealt together", "", "| These | Against these | Why |", "|---|---|---|");
  for (const entry of input.contested) lines.push(`| ${cell(entry.a.map(name).join("; "))} | ${cell(entry.b.map(name).join("; "))} | ${cell(entry.reason)} |`);
  return `${lines.join("\n")}\n`;
}
