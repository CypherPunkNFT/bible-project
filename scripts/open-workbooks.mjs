// The open-workbooks table (Research/Resources/OpenWorkbooks): free Bible-study materials by other people that the
// site may hand out with credit. One row per title, with who it is for, what it is about and the exact words that
// allow us to share it. Nothing here is downloaded; a row reaches "approved" only on the owner's word.
//
//   node scripts/open-workbooks.mjs check            validate every row and rewrite TABLE.md
//   node scripts/open-workbooks.mjs add <file.json>  append new candidates (duplicates skipped), then check
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "../../Research/Resources/OpenWorkbooks");
const tablePath = join(dir, "open-workbooks.json");
const catalogue = JSON.parse(readFileSync(join(here, "../src/data/resources/learning-catalogue.json"), "utf8"));

const DOORS = catalogue.audiences.map((a) => a.id);
const SUBJECTS = catalogue.tracks.map((t) => t.id);
const KINDS = catalogue.kinds.map((k) => k.id);
const BASES = ["public-domain", "open-licence", "publisher-permission"];
const STATUSES = ["candidate", "approved", "downloaded", "rejected"];
const CHECKS = ["passes", "needs-review", "fails"];
const TRI = [true, false, "unclear"];

const slug = (s) => s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 70);
const isUrl = (s) => typeof s === "string" && /^https?:\/\/\S+$/.test(s);
const load = () => JSON.parse(readFileSync(tablePath, "utf8"));

function problems(row) {
  const out = [], r = row.rights ?? {}, t = row.tradition ?? {};
  const need = (ok, what) => { if (!ok) out.push(what); };
  need(row.id && row.title, "id and title");
  need(row.author || row.publisher, "author or publisher");
  need(Array.isArray(row.doors) && row.doors.length && row.doors.every((d) => DOORS.includes(d)), `doors from ${DOORS.join("/")}, got ${JSON.stringify(row.doors)}`);
  need(KINDS.includes(row.kind), `kind from ${KINDS.join("/")}, got ${JSON.stringify(row.kind)}`);
  need(Array.isArray(row.subjects) && row.subjects.every((s) => SUBJECTS.includes(s)), `subjects from ${SUBJECTS.join("/")}, got ${JSON.stringify(row.subjects)}`);
  need(BASES.includes(r.basis), `rights.basis from ${BASES.join("/")}, got ${JSON.stringify(r.basis)}`);
  need(r.licence, "rights.licence");
  need(r.basis === "public-domain" || r.permissionText, "rights.permissionText (the exact words that allow sharing)");
  need(r.basis === "public-domain" || isUrl(r.licenceUrl), `rights.licenceUrl as a web address, got ${JSON.stringify(r.licenceUrl)}`);
  need(TRI.includes(r.canHandOut), `rights.canHandOut true/false/"unclear", got ${JSON.stringify(r.canHandOut)}`);
  need(CHECKS.includes(t.doctrinalCheck), `tradition.doctrinalCheck from ${CHECKS.join("/")}, got ${JSON.stringify(t.doctrinalCheck)}`);
  need(isUrl(row.sourcePage), `sourcePage as a web address, got ${JSON.stringify(row.sourcePage)}`);
  need(STATUSES.includes(row.status), `status from ${STATUSES.join("/")}, got ${JSON.stringify(row.status)}`);
  return out;
}

function add(files, today) {
  const rows = load(), byKey = new Map();
  for (const r of rows) { byKey.set(r.id, r); byKey.set(`${r.sourcePage}|${slug(r.title)}`, r); if (r.downloadUrl) byKey.set(r.downloadUrl, r); }
  const union = (a = [], b = []) => [...new Set([...a, ...b])];
  let added = 0, merged = 0;
  for (const file of files) for (const item of JSON.parse(readFileSync(file, "utf8"))) {
    const id = slug(`${item.title} ${item.author || item.publisher || ""}`), page = `${item.sourcePage}|${slug(item.title)}`;
    // A title found again for another door keeps its first row and gains the new doors and subjects.
    const known = byKey.get(id) ?? byKey.get(page) ?? (item.downloadUrl && byKey.get(item.downloadUrl));
    if (known) { known.doors = union(known.doors, item.doors); known.subjects = union(known.subjects, item.subjects); merged++; continue; }
    const row = { id, ...item, status: "candidate", found: today };
    rows.push(row); byKey.set(id, row); byKey.set(page, row); if (row.downloadUrl) byKey.set(row.downloadUrl, row);
    added++;
  }
  writeFileSync(tablePath, JSON.stringify(rows, null, 2) + "\n", "utf8");
  console.log(`added ${added}, merged ${merged} already in the table`);
}

const yesNo = (v) => (v === true ? "yes" : v === false ? "**no**" : "unclear");
const cell = (s) => String(s ?? "").replace(/\|/g, "/").replace(/\s+/g, " ");

function table(rows) {
  const name = Object.fromEntries(catalogue.audiences.map((a) => [a.id, `${a.name} (${a.age})`]));
  const count = (f) => rows.filter(f).length;
  const lines = ["# Open workbooks: the table", "",
    "Generated by `node scripts/open-workbooks.mjs check` from [open-workbooks.json](open-workbooks.json). Do not edit by hand; see [README.md](README.md).", "",
    `**${rows.length} titles.** Public domain ${count((r) => r.rights.basis === "public-domain")} · open licence ${count((r) => r.rights.basis === "open-licence")} · publisher permission ${count((r) => r.rights.basis === "publisher-permission")}. ` +
    `Status: ${STATUSES.map((s) => `${s} ${count((r) => r.status === s)}`).join(" · ")}.`, "",
    "| Door | Titles | We may hand out | Doctrine passes |", "|---|---|---|---|",
    ...DOORS.map((d) => { const here = rows.filter((r) => r.doors.includes(d)); return `| ${name[d]} | ${here.length} | ${here.filter((r) => r.rights.canHandOut === true).length} | ${here.filter((r) => r.tradition.doctrinalCheck === "passes").length} |`; }), ""];
  for (const d of DOORS) {
    const here = rows.filter((r) => r.doors.includes(d));
    if (!here.length) continue;
    lines.push(`## ${name[d]}`, "", "| Title | By | Kind · ages | Rights | Hand out? | Doctrine | Status |", "|---|---|---|---|---|---|---|");
    for (const r of here) lines.push(`| [${cell(r.title)}](${r.sourcePage}) | ${cell(r.author || r.publisher)} | ${r.kind} · ${cell(r.ages)} | ${r.rights.licenceUrl ? `[${cell(r.rights.licence)}](${r.rights.licenceUrl})` : cell(r.rights.licence)} | ${yesNo(r.rights.canHandOut)} | ${r.tradition.doctrinalCheck} | ${r.status} |`);
    lines.push("");
  }
  const look = rows.filter((r) => r.rights.canHandOut !== true || r.tradition.doctrinalCheck !== "passes");
  if (look.length) {
    lines.push("## Needs a look before use", "", "| Title | Why |", "|---|---|");
    for (const r of look) lines.push(`| ${cell(r.title)} | ${cell([r.rights.canHandOut !== true && `Sharing: ${yesNo(r.rights.canHandOut)}. ${r.rights.conditions ?? ""}`, r.tradition.doctrinalCheck !== "passes" && `Doctrine ${r.tradition.doctrinalCheck}: ${r.tradition.note ?? ""}`].filter(Boolean).join(" "))} |`);
    lines.push("");
  }
  return lines.join("\n");
}

const [command, ...files] = process.argv.slice(2);
if (command === "add") add(files, new Date().toISOString().slice(0, 10));
else if (command !== "check") { console.error(`unknown command ${JSON.stringify(command)}: expected "check" or "add <file.json>"`); process.exit(2); }
const rows = load();
const bad = rows.map((r) => [r.id ?? r.title, problems(r)]).filter(([, p]) => p.length);
for (const [id, p] of bad) console.error(`${id}: needs ${p.join("; ")}`);
// A row with problems is left out of the view until it is fixed, so the view never shows a half-checked title.
writeFileSync(join(dir, "TABLE.md"), table(rows.filter((r) => !problems(r).length)), "utf8");
console.log(`${rows.length} rows, ${bad.length} with problems (left out of TABLE.md); TABLE.md written`);
process.exit(bad.length ? 1 : 0);
