// Refresh the local-only mockup from the canonical, owner-supplied transcript.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const index = JSON.parse(readFileSync(new URL('content/apologetics/transcripts/index.json', root), 'utf8'));
const record = index['lennox-dawkins'];
const bytes = readFileSync(new URL(`content/apologetics/transcripts/${record.file}`, root));
if (createHash('sha256').update(bytes).digest('hex') !== record.sha256) throw new Error('Transcript differs from its provenance record.');
const output = new URL('design/debate-viewer/transcript-data.js', root);
const content = '// Generated by scripts/build-debate-viewer.mjs. Edit the canonical transcript records, not this file.\n' +
  `window.debateTranscript=${JSON.stringify({ ...record, text: bytes.toString('utf8') })};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== content) throw new Error('Mockup transcript needs regeneration.');
  console.log('Mockup transcript matches the saved original and provenance record.');
} else {
  writeFileSync(output, content);
  console.log(`Saved ${record.words} words for both mockups: ${fileURLToPath(output)}`);
}
