// Bible Firsts (category 8, design §4.8): one question, the answer and two or three wrong options. Only firsts that
// Scripture states (a verse says first, firstborn, firstfruits, beginning or began) or plainly shows; never a defensible wrong option.
import { type Span, type Tier } from "../../src/pages/games/what-came-first/order.ts";
import { loadPeople } from "../whos-older/site-data.ts";
import { Log, checkMatch, checkSpans, readSource, sourcesHash, spanText, usedBooks, type LeftOut } from "./common.ts";

const FIRST_WORDS = /\b(first|firstborn|firstfruits|beginning|began)\b/i;
/** The owner's exclusions (brief §1): the days of Creation, the plagues, which book was written first, which miracle came first. */
const OFF_LIMITS = /\b(plague|days? of creation|written first|first written|miracle)\b/i;
const MIN_QUESTIONS = 15;

export interface SourceQuestion { id: string; question: string; tier: Tier; answer: string; options: string[]; never?: string[];
  refs: Span[]; evidence: "states" | "shows"; match: string; why: string; answerId?: string }
interface FirstsSource { questions: SourceQuestion[]; leftOut: LeftOut[] }

export interface FirstsResult { log: Log; questions: SourceQuestion[]; leftOut: LeftOut[]; body: Record<string, unknown> & { about: string } }

const norm = (text: string) => text.toLowerCase().replace(/[‘’]/g, "'").replace(/[^a-z0-9' ]+/g, " ").replace(/\s+/g, " ").trim();

export function buildFirsts(): FirstsResult {
  const log = new Log("firsts");
  const { text, data: source } = readSource<FirstsSource>("firsts.source.json");
  const people = loadPeople();
  const ids = new Set<string>();
  const wordings = new Set<string>();
  for (const q of source.questions) {
    const at = `question ${q.id}`;
    if (!q.id?.startsWith("first-")) log.error(`${at}: ids start with "first-"`);
    if (ids.has(q.id)) log.error(`${at}: id used twice`);
    ids.add(q.id);
    if (!q.question?.trim().endsWith("?")) log.error(`${at}: the question must end with a question mark`);
    if (wordings.has(norm(q.question))) log.error(`${at}: the same question is asked twice`);
    wordings.add(norm(q.question));
    if (OFF_LIMITS.test(q.question)) log.error(`${at}: asks about something the owner left out of this game`);
    if (![1, 2, 3].includes(q.tier)) log.error(`${at}: tier must be 1, 2 or 3`);
    if (!q.answer?.trim() || !q.why?.trim()) log.error(`${at}: answer and why are required`);
    if (!Array.isArray(q.options) || q.options.length < 2 || q.options.length > 3) log.error(`${at}: 2 or 3 wrong options are required, got ${q.options?.length}`);
    const seen = new Set([norm(q.answer)]);
    const never = new Set((q.never ?? []).map(norm));
    for (const option of q.options ?? []) {
      if (seen.has(norm(option))) log.error(`${at}: option "${option}" repeats the answer or another option`);
      if (never.has(norm(option))) log.error(`${at}: option "${option}" is on the question's never list (a defensible answer)`);
      seen.add(norm(option));
    }
    if (!checkSpans(log, at, q.refs)) continue;
    checkMatch(log, at, q.refs, q.match);
    if (q.evidence !== "states" && q.evidence !== "shows") log.error(`${at}: evidence must be "states" or "shows"`);
    if (q.evidence === "states" && !FIRST_WORDS.test(spanText(q.refs))) log.error(`${at}: says Scripture states it, but no verse has first, firstborn, firstfruits, beginning or began`);
    if (q.answerId && !people.has(q.answerId)) log.error(`${at}: answerId ${q.answerId} is not in data/study/people.json`);
  }
  for (const l of source.leftOut) if (!l.name?.trim() || !l.reason?.trim()) log.error(`left-out entry needs a name and a reason: ${JSON.stringify(l)}`);
  if (source.questions.length < MIN_QUESTIONS) log.error(`only ${source.questions.length} questions (at least ${MIN_QUESTIONS} needed)`);
  const body = {
    about: "Generated by scripts/build-what-came-first.ts from src/data/what-came-first/firsts.source.json; do not edit.",
    sources: sourcesHash([text]),
    category: "firsts",
    books: usedBooks(source.questions.flatMap((q) => q.refs)),
    questions: source.questions.map(({ id, question, tier, answer, options, refs, evidence, why, answerId }) =>
      ({ id, question, tier, answer, options, refs, evidence, why, ...(answerId ? { answerId } : {}) })),
  };
  return { log, questions: source.questions, leftOut: source.leftOut, body };
}
