// Which comes first in your Bible? (category 7, design §4.7): generated from the 66-book Protestant order the site's
// catalogue already uses (data/catalog.json; Genesis 1 ... Revelation 66, the numbers in every verse id). No research,
// no disputes, no blocked pairs. The game shows each book's name as the reader's own Bible names it; the English names
// here are a fallback only.
import { type Item } from "../../src/pages/games/what-came-first/order.ts";
import { Log, books, checkBandMinimum, settlePool, type Pool } from "./common.ts";

const SECTIONS = ["history", "poetry", "prophets", "gospels", "epistles", "revelation"];
const MIN_PER_BAND = 300;

export type BookItem = Item & { code: string; section: string };
export interface BooksResult { log: Log; pool: Pool<BookItem>; body: Record<string, unknown> & { about: string } }

export function buildBooks(): BooksResult {
  const log = new Log("books");
  const list = [...books.values()].sort((a, b) => a.num - b.num) as { num: number; code: string; name: string; section?: string }[];
  if (list.length !== 66) log.error(`expected 66 books, found ${list.length}`);
  list.forEach((book, index) => {
    if (book.num !== index + 1) log.error(`book ${book.code} is number ${book.num}, expected ${index + 1} (no gaps)`);
    if (!SECTIONS.includes(book.section ?? "")) log.error(`book ${book.code} has section ${book.section}, expected one of ${SECTIONS.join(", ")}`);
  });
  const items: BookItem[] = list.map((book) => ({ id: book.code, code: book.code, label: book.name, tier: 1, lo: null, hi: null, shown: true,
    position: book.num, testament: book.num <= 39 ? "old" : "new", section: book.section ?? "" }));
  const pool = settlePool(log, "books", items, [], [], 65);
  if (pool.orders.length !== (66 * 65) / 2) log.error(`expected 2,145 pairs, found ${pool.orders.length}`);
  checkBandMinimum(log, pool.perBand, MIN_PER_BAND);
  const body = {
    about: "Generated by scripts/build-what-came-first.ts from the site's catalogue (data/catalog.json); do not edit. The game shows each book's name in the reader's own Bible.",
    category: "books",
    items: pool.items.map(({ id, label, position, testament, section }) => ({ id, label, position, testament, section })),
  };
  return { log, pool, body };
}
