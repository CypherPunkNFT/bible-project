"""Generate the Hymns pages' stylesheets from the approved mock-ups' own CSS, so the live pages look exactly like them.

  src/pages/study/hymns/mockup-collection.css  from design/authors-directions/shared/frame.css (page pieces only),
                                               teachers/teachers.css, bible.css, through.css and
                                               design/hymn-directions/collection/collection.css, catalogue.css
  src/pages/study/hymns/song/mockup-song.css   from frame.css (page pieces only) and design/hymn-directions/shared/hymn.css, echoes.css,
                                               constellation.css, hymn-page.css

Every rule is scoped under the page's root class (.hy-page, .hy-song), so nothing here reaches another page and no
other page's styles reach these. The mock-up frame's site chrome (header, footer, palette, fonts) is left out: the site
provides its own. The mock-up's outside-scroll classes (.os-*) are renamed to the site's OutsideScroll component's.
Hand-written additions live in hymns.css and song/song.css, never here. Re-run after the mock-up's CSS changes:
    py -3.12 scripts/build-hymn-styles.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
SITE = Path(__file__).resolve().parents[1]
DESIGN = SITE / "design"
OUT = SITE / "src/pages/study/hymns"

# The mock-up's outside scroll (design/hymn-directions/shared/outside-scroll.js) and the site's component, class by class.
OS_RENAME = [(".os-area", ".outside-scroll-area"), (".os-frame", ".outside-scroll-frame"), (".os-viewport", ".outside-scroll-viewport"),
             (".os-content", ".outside-scroll-content"), (".os-bar", ".outside-scrollbar"), (".os-extent", ".w-px")]
# Frame rules that are site chrome or the palette: the live site has its own.
CHROME = re.compile(r"^(html|:root|main|\.site-header|\.strip|\.bar|\.logo|\.nav|\.search-btn|\.theme-switch|\.site-footer|\.foot-|\.chart-link|\.open-chart)")
# Rules the chosen page leaves out: the mock-ups' A/B/C switch and the variants the owner set aside.
SET_ASIDE = re.compile(r"^(\.hy-switch|\.hp-mode|\.hp-whole|\.hp-st|\.ec\.hp-)")


def strip_comments(css: str) -> str:
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def blocks(css: str):
    i = 0
    while True:
        start = css.find("{", i)
        if start < 0:
            return
        depth, j = 1, start + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        yield css[i:start].strip(), css[start + 1:j - 1]
        i = j


def scope_selector(sel: str, root: str) -> str | None:
    sel = sel.strip()
    if not sel or CHROME.match(sel) or SET_ASIDE.match(sel):
        return None
    for old, new in OS_RENAME:
        sel = sel.replace(old, new)
    if sel == "body":
        return root
    if sel.startswith("body "):
        return f"{root} {sel[5:]}"
    return f"{root} {sel}"


def scope(css: str, root: str) -> str:
    out = []
    for prelude, body in blocks(css):
        if prelude.startswith(("@media", "@supports")):
            inner = scope(body, root)
            if inner.strip():
                out.append(f"{prelude} {{\n{inner}}}\n")
        elif prelude.startswith("@font-face"):
            continue
        elif prelude.startswith("@"):
            out.append(f"{prelude} {{{' '.join(body.split())}}}\n")
        elif prelude == "body" and "100dvh" in body:
            continue  # the frame's sticky-footer layout: page chrome, not the page
        else:
            sels = [s for s in (scope_selector(x, root) for x in split_selectors(prelude)) if s]
            if sels:
                out.append(f"{', '.join(sels)} {{ {' '.join(body.split())} }}\n")
    return "".join(out)


def split_selectors(prelude: str) -> list[str]:
    """Split on top-level commas only (":is(a, b)" stays whole)."""
    parts, depth, cur = [], 0, ""
    for ch in prelude:
        depth += {"(": 1, ")": -1}.get(ch, 0)
        if ch == "," and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    return parts + [cur]


def build(files: list[Path], root: str, target: Path, lead: str) -> None:
    text = lead + "".join(f"\n/* ── from {f.relative_to(SITE).as_posix()} ── */\n" + scope(strip_comments(f.read_text(encoding="utf-8")), root) for f in files)
    assert "hy-switch" not in text and ".os-" not in text, f"{target.name}: a set-aside or unrenamed rule slipped through"
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"{target.relative_to(SITE).as_posix()}: {text.count('{')} rules")


HEAD = "/* Generated by scripts/build-hymn-styles.py from the approved mock-up's CSS. Do not edit; hand additions go in {}. */\n"
build([DESIGN / "authors-directions/shared/frame.css", DESIGN / "authors-directions/teachers/teachers.css", DESIGN / "authors-directions/teachers/bible.css",
       DESIGN / "authors-directions/teachers/through.css", DESIGN / "hymn-directions/collection/collection.css", DESIGN / "hymn-directions/collection/catalogue.css"],
      ".hy-page", OUT / "mockup-collection.css", HEAD.format("hymns.css"))
build([DESIGN / "authors-directions/shared/frame.css", *(DESIGN / f"hymn-directions/shared/{n}" for n in ["hymn.css", "echoes.css", "constellation.css", "hymn-page.css"])],
      ".hy-song", OUT / "song/mockup-song.css", HEAD.format("song/song.css"))
