// Who's older? build: the owner's review sheet, docs/features/whos-older/review-sheet.md (design §4.6). Every
// window beside the other sources, every fact, every warning with its resolution note (or none yet).
import type { Band, Fact, Span } from "../../src/pages/games/whos-older/pairing.ts";
import type { PageBounds } from "./checks.ts";

export interface SheetWarning { id: string; text: string; needsNote: boolean }

interface SheetCharacter { id: string; label: string; tier: number; born: { lo: number | null; hi: number | null }; shown?: boolean; pageAge?: [number, number]; pageSkip?: string }
interface SheetPerson { id: string; label: string }

export interface SheetInput {
  characters: SheetCharacter[];
  pool: SheetPerson[];
  facts: Fact[];
  blocked: { a: string; b: string; reason: string }[];
  perBand: Record<Band, number>;
  pairCount: number;
  warnings: SheetWarning[];
  resolutions: Record<string, string>;
  notices: string[];
  bounds: Map<string, PageBounds>;
  theoYear: Map<string, number>;
  periods: Map<string, string>;
}

const year = (y: number | null) => (y === null ? "open" : y < 0 ? `${-y} BC` : `AD ${y}`);
const cell = (text: string) => text.replace(/\|/g, "\\|");
const spans = (refs: Span[]) => refs.map(([a, b]) => (a === b ? String(a) : `${a}–${b}`)).join(", ");

export function reviewSheet(input: SheetInput): string {
  const inPool = new Set(input.pool.map((p) => p.id));
  const name = new Map(input.characters.map((c) => [c.id, c.label]));
  const label = (id: string) => name.get(id) ?? id;
  const unresolved = input.warnings.filter((w) => w.needsNote && !input.resolutions[w.id]);
  const out: string[] = [
    "# Who's older? — review sheet",
    "",
    "Generated by `scripts/build-whos-older.ts`; do not edit. Change the source files in `src/data/whos-older/` and run",
    "`node --experimental-strip-types scripts/build-whos-older.ts` again. Design: [design.md](design.md) §4.",
    "",
    `**${input.pool.length} people**, ${input.facts.filter((f) => !f.derived).length} hand facts, ${input.facts.filter((f) => f.derived).length} facts from the family links, ` +
      `**${input.pairCount} askable pairs**: Easy ${input.perBand.easy}, Medium ${input.perBand.medium}, Hard ${input.perBand.hard}.`,
    "",
    "## Warnings",
    "",
    `${input.warnings.length} warning(s); **${unresolved.length} still need a one-line note** before release. A note goes in`,
    "`characters.source.json` under `resolutions`, keyed by the warning's id.",
    "",
  ];
  if (!input.warnings.length) out.push("None.", "");
  else {
    out.push("| Id | Warning | Note |", "|---|---|---|");
    for (const w of [...input.warnings].sort((a, b) => Number(!!input.resolutions[a.id]) - Number(!!input.resolutions[b.id]))) {
      const note = input.resolutions[w.id] ?? (w.needsNote ? "**needs a note**" : "(information only)");
      out.push(`| \`${w.id}\` | ${cell(w.text)} | ${cell(note)} |`);
    }
    out.push("");
  }
  if (input.notices.length) out.push("## Notices", "", ...input.notices.map((n) => `- ${n}`), "");

  out.push("## People", "", "Window = the hand-kept birth window. Page needs = the range the people-page's reign dates demand (check 6).",
    "", "| Person | Id | Tier | Window | Page needs | Theographic | Period |", "|---|---|---|---|---|---|---|");
  for (const c of input.characters) {
    const bounds = input.bounds.get(c.id);
    const page = c.pageSkip ? `skipped: ${c.pageSkip}` : bounds ? `${year(bounds.lo)} – ${year(bounds.hi)} (${bounds.how})` : "—";
    const window = c.shown === false ? `order only (${c.born.lo}..${c.born.hi})` : `${year(c.born.lo)} – ${year(c.born.hi)}`;
    const theo = input.theoYear.has(c.id) ? year(input.theoYear.get(c.id)!) : "—";
    const left = inPool.has(c.id) ? "" : " *(left out)*";
    out.push(`| ${cell(c.label)}${left} | \`${c.id}\` | ${c.tier} | ${window} | ${cell(page)} | ${theo} | ${input.periods.get(c.id) ?? "—"} |`);
  }

  out.push("", "## Hand facts", "", "| First | Second | Kind | Verses | Why |", "|---|---|---|---|---|");
  for (const f of input.facts.filter((f) => !f.derived)) out.push(`| ${label(f.first)} | ${label(f.second)} | ${f.kind} | ${spans(f.refs)} | ${cell(f.why)} |`);

  out.push("", "## Derived from family links", "", "Strike a wrong one by adding the pair to `blocked-pairs.source.json`.", "",
    "| Elder | Younger | Kind | Explanation |", "|---|---|---|---|");
  for (const f of input.facts.filter((f) => f.derived)) out.push(`| ${label(f.first)} | ${label(f.second)} | ${f.kind} | ${cell(f.why)} |`);

  out.push("", "## Blocked pairs", "", "| Pair | Reason |", "|---|---|");
  for (const b of input.blocked) out.push(`| ${label(b.a)} / ${label(b.b)} | ${cell(b.reason)} |`);
  return `${out.join("\n")}\n`;
}
