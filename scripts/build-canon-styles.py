"""Generate the canon study's stylesheet from the approved mock-up's own CSS, so the live page looks exactly like it.

  src/pages/study/canon/mockup-canon.css  from the stylesheets design/canon-directions/index.html loads: the Authors
                                          frame (page pieces only) and teachers.css, the Manuscripts mock-up's ms.css,
                                          and the canon mock-up's cn.css and cn-sections.css

The live page is direction D, "One story" (design/canon-directions/?d=d), approved by the owner on 2026-10-20. Every rule
is scoped under the page's root class (.cn-root); the frame's site chrome and the mock-up's direction switch are left
out. The scoping itself is scripts/build-manuscript-styles.py's, reused here. Hand-written additions live in canon.css,
never here. Re-run after the mock-up's CSS changes:
    py -3.12 scripts/build-canon-styles.py
"""
from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")
SITE = Path(__file__).resolve().parents[1]
DESIGN = SITE / "design"
TARGET = SITE / "src/pages/study/canon/mockup-canon.css"
ROOT = ".cn-root"
FILES = ["authors-directions/shared/frame.css", "authors-directions/teachers/teachers.css",
         "manuscripts-directions/css/ms.css", "canon-directions/css/cn.css", "canon-directions/css/cn-sections.css"]


def load_scoper():
    path = SITE / "scripts/build-manuscript-styles.py"
    spec = importlib.util.spec_from_file_location("manuscript_styles", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"build-canon-styles: could not load the scoping functions from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.ROOT = ROOT
    # Only the direction switch is set aside: the mock-up drew D with every other rule these files hold.
    module.SET_ASIDE = re.compile(r"^\.dir-switch")
    return module


def main() -> None:
    scoper = load_scoper()
    lead = "/* Generated by scripts/build-canon-styles.py from the approved mock-up's CSS. Do not edit; hand additions go in canon.css. */\n"
    text = lead + "".join(f"\n/* ── from design/{name} ── */\n" + scoper.scope(scoper.strip_comments((DESIGN / name).read_text(encoding="utf-8")))
                          for name in FILES)
    bad = [line for line in text.splitlines() if "dir-switch" in line or f"{ROOT} :root" in line]
    if bad:
        raise ValueError(f"{TARGET.name}: a set-aside or mis-scoped rule slipped through: {bad[:3]}")
    TARGET.write_text(text, encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(SITE).as_posix()}: {text.count('{')} rules")


if __name__ == "__main__":
    main()
