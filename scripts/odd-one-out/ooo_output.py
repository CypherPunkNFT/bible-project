"""Odd one out: the shipped files (design 4, 6.5 and 6.7): sets.json, facts-table.json and the review sheet."""
import hashlib
import json

from ooo_construct import MIN_SETS, Builder, set_id
from ooo_data import Bible, Catalogue
from ooo_model import DIFFICULTIES, KINDS, Candidate, Item, Rule

KIND_TITLES = {"person": "People", "place": "Places", "book": "Books"}


def dumps(value) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def write_lines(document: dict) -> str:
    """JSON with one entry per line for the big maps and lists, so a rebuild's diff stays readable."""
    lines = []
    for key, value in document.items():
        if isinstance(value, dict) and len(value) > 3:
            body = ",\n".join(f"  {dumps(k)}:{dumps(v)}" for k, v in value.items())
            lines.append(f" {dumps(key)}:{{\n{body}\n }}")
        elif isinstance(value, list) and len(value) > 3:
            body = ",\n".join(f"  {dumps(v)}" for v in value)
            lines.append(f" {dumps(key)}:[\n{body}\n ]")
        else:
            lines.append(f" {dumps(key)}:{dumps(value)}")
    return "{\n" + ",\n".join(lines) + "\n}\n"


def rule_entry(rule: Rule, bible: Bible) -> dict:
    entry = {"kind": rule.kind, "members": rule.members, "odd": rule.odd}
    if rule.odd_only:
        entry |= {"oddOnly": rule.odd_only, "others": rule.others}
    if rule.key_ref:
        entry |= {"keyRef": list(rule.key_ref), "keyQuote": bible.quote(*rule.key_ref)}
    return entry


def set_entry(candidate: Candidate, items: dict[str, Item]) -> dict:
    entry = {"id": set_id(candidate.rule, candidate.polarity, candidate.items), "kind": candidate.kind,
             "difficulty": candidate.difficulty, "items": candidate.items, "odd": candidate.odd,
             "rule": candidate.rule, "polarity": candidate.polarity}
    if candidate.labels:
        entry["labels"] = candidate.labels
    facts = {i: items[i].proof[candidate.rule] for i in candidate.items
             if candidate.rule in items[i].proof and items[i].proof[candidate.rule] != items[i].ref}
    if facts:
        entry["facts"] = facts
    if candidate.also:
        entry["also"] = candidate.also
    return entry


def ordered_sets(builders: list[Builder]) -> list[Candidate]:
    """Seed sets first, then by kind, difficulty and id, so the file does not depend on build order."""
    rank = {d: n for n, d in enumerate(DIFFICULTIES)}
    every = [s for b in builders for s in b.sets]
    return sorted(every, key=lambda s: (not s.seed, KINDS.index(s.kind), rank[s.difficulty],
                                        set_id(s.rule, s.polarity, s.items)))


def check_refs(candidates: list[Candidate], items: dict[str, Item], bible: Bible) -> None:
    for candidate in candidates:
        for item_id in candidate.items:
            item = items[item_id]
            for verse in [item.ref, *item.proof.values()]:
                if bible.text(verse) is None:
                    raise ValueError(f"{item_id}: verse {verse} is not in the BSB text")


def sets_document(builders: list[Builder], rules: list[Rule], catalogue: Catalogue, bible: Bible) -> dict:
    items = {i: item for b in builders for i, item in b.items.items()}
    candidates = ordered_sets(builders)
    check_refs(candidates, items, bible)
    used = sorted({i for c in candidates for i in c.items})
    used_rules = {c.rule for c in candidates}
    body = {
        "books": [[b["code"], b["name"]] for b in catalogue.books],
        "rules": {r.id: rule_entry(r, bible) for r in rules if r.id in used_rules},
        "items": {i: {"kind": items[i].kind, "label": items[i].label, "brief": items[i].brief,
                      "href": items[i].href, "ref": items[i].ref} for i in used},
        "sets": [set_entry(c, items) for c in candidates],
    }
    stamp = hashlib.sha256(dumps(body).encode()).hexdigest()[:12]
    head = {"about": "Odd one out sets. Generated by scripts/build-odd-one-out.py; do not edit.", "version": 1,
            "stamp": stamp, "minSets": MIN_SETS, "first": body["sets"][0]["id"]}
    return head | body


def facts_table(builders: list[Builder], used: set[str], book_words: set[str]) -> dict:
    """Every shipped item's facts as true and unknown property indexes, for the second solver (design 6.7)."""
    kinds = {}
    for builder in builders:
        prop_ids = sorted({p for i in used if i in builder.items for p in builder.items[i].values})
        props = [{"id": p} | ({"anchor": builder.props[p].anchor} if builder.props[p].anchor else {}) for p in prop_ids]
        index = {p: n for n, p in enumerate(prop_ids)}
        table = {}
        for item_id in sorted(i for i in used if i in builder.items):
            item = builder.items[item_id]
            table[item_id] = {"name": item.name,
                              "t": sorted(index[p] for p, v in item.values.items() if v is True),
                              "u": sorted(index[p] for p, v in item.values.items() if v is None)}
        kinds[builder.kind] = {"props": props, "items": table}
    return {"about": "Odd one out fact table for the test suite's independent solver. Generated by "
                     "scripts/build-odd-one-out.py; do not edit. t = true, u = unknown, anything else false.",
            "bookWords": sorted(book_words), "kinds": kinds}


def headline(entry: dict, rules: dict, items: dict) -> str:
    labels = {i: entry.get("labels", {}).get(i, items[i]["label"]) for i in entry["items"]}
    others = [labels[i] for i in entry["items"] if i != entry["odd"]]
    rule = rules[entry["rule"]]
    if entry["polarity"] == "members-share":
        return f"**{labels[entry['odd']]}** {rule['odd']}. {', '.join(others[:2])} and {others[2]} {rule['members']}."
    return f"**{labels[entry['odd']]}** {rule['oddOnly']}. {', '.join(others[:2])} and {others[2]} {rule['others']}."


def review_sheet(document: dict) -> str:
    rules, items = document["rules"], document["items"]
    lines = ["# Odd one out: review sheet", "",
             "Generated by `scripts/build-odd-one-out.py`; do not edit. One line per shipped set. To drop a set, add its id "
             "to `scripts/odd-one-out/veto.json` with a reason and rebuild (design section 6.5).", ""]
    for kind in KINDS:
        for difficulty in DIFFICULTIES:
            rows = [s for s in document["sets"] if s["kind"] == kind and s["difficulty"] == difficulty]
            hidden = " (hidden: fewer than %d sets)" % MIN_SETS if len(rows) < MIN_SETS else ""
            lines += [f"## {KIND_TITLES[kind]}, {difficulty}: {len(rows)} sets{hidden}", "",
                      "| Set | The four | Answer and reason | Also true |", "|---|---|---|---|"]
            for s in rows:
                four = ", ".join(s.get("labels", {}).get(i, items[i]["label"]) for i in s["items"])
                also = "; ".join(s.get("also", [])) or "–"
                lines.append(f"| {s['id']} | {four} | {headline(s, rules, items)} | {also} |")
            lines.append("")
    return "\n".join(lines)


def counts(document: dict) -> dict[str, dict[str, int]]:
    out = {k: {d: 0 for d in DIFFICULTIES} for k in KINDS}
    for s in document["sets"]:
        out[s["kind"]][s["difficulty"]] += 1
    return out
