import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
const facts=JSON.parse(readFileSync('content/teachers/contributor-facts.json','utf8')); 
const usage=JSON.parse(readFileSync('content/teachers/feature-usage.json','utf8')) as {features:{sources:unknown[]}[]};
const count=(n:number)=>n.toLocaleString('en-US');
test('all sections keep their established visual forms with current data',async({page})=>{
 await page.goto('/teachers/scholars');
 await page.locator('#catalogue').scrollIntoViewIfNeeded();
 await expect(page.locator('.cat-count')).toContainText(count(facts.summary.catalogueEntries));
 await expect(page.locator('.idea-lineage [role=tab]')).toHaveCount(5);
 await expect(page.locator('.lnd-figs')).toContainText(count(facts.summary.eras.unknown));
 const built=page.locator('#built'); await built.scrollIntoViewIfNeeded();
 await expect(built.locator('.blt-feat')).toHaveCount(usage.features.length);
 await expect(built.locator('.blt-rib')).toHaveCount(usage.features.reduce((n,f)=>n+f.sources.length,0));
 await expect(built.locator('.blt-work').first()).toHaveAttribute('href',/^https:/);
 await page.locator('#discoveries').scrollIntoViewIfNeeded();
 await expect(page.locator('.dsc-mapcard')).toHaveCount(1);
 await expect(page.locator('.dsc-find')).toHaveCount(8);
 const named=page.locator('#named');await named.scrollIntoViewIfNeeded();
 await expect(named.locator('.nmd-rows li')).toHaveCount(96);
 await expect(named.locator('.nmd-cell')).toHaveCount(96*5);
 await named.locator('.nmd-grid').evaluate(el=>{el.scrollTop=(el.scrollHeight-el.clientHeight)*.45});
 await expect(named.locator('.nmd-rows li')).toHaveCount(192);
 const numbers=page.locator('#numbers');await numbers.scrollIntoViewIfNeeded();
 await expect(numbers.locator('.num-card')).toHaveCount(4);
 await expect(numbers.locator('h2')).toContainText(count(facts.summary.catalogueEntries));
 for(const [era,n] of Object.entries(facts.summary.eras))await expect(numbers.locator(`[data-facet=era][data-value="${era}"] .num-n`)).toHaveText(count(Number(n)));
 await numbers.locator('[data-facet=era][data-value=unknown]').click();
 await expect(page.locator('.cat-count b')).toHaveText(count(facts.summary.eras.unknown));
 const directory=page.locator('#directory');await directory.scrollIntoViewIfNeeded();
 await expect(directory.locator('h2')).toContainText(count(facts.summary.catalogueEntries));
 await expect(directory.locator('.dir-list li')).toHaveCount(96);
 await directory.locator('.dir-frame').evaluate(el=>{el.scrollTop=(el.scrollHeight-el.clientHeight)*.45});
 await expect(directory.locator('.dir-list li')).toHaveCount(192);
 await directory.getByRole('button',{name:'A to Z',exact:true}).click();
 await expect(directory.locator('.dir-list li')).toHaveCount(96);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1);
 await expect(page.locator('.usage-card,.credit-browser')).toHaveCount(0);
});
