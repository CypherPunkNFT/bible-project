const DAYS_IN_MONTH = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

/** Every "MM-DD" of a year that has a 29 February: 366 of them, in order. */
export function allBirthdayDates(): string[] {
  return DAYS_IN_MONTH.flatMap((days, month) =>
    Array.from({ length: days }, (_, day) => `${String(month + 1).padStart(2, "0")}-${String(day + 1).padStart(2, "0")}`));
}

/** The "MM-DD" of a date field's value ("2026-03-14" -> "03-14"), read from the text so no time zone can shift it. */
export function monthDayOf(value: string): string | null {
  const match = /^\d{4}-(\d{2})-(\d{2})$/.exec(value);
  if (!match) return null;
  const key = `${match[1]}-${match[2]}`;
  return allBirthdayDates().includes(key) ? key : null;
}

/** True once every date has its verse: only then does the picker offer the date field. */
export const birthdayDatesComplete = (record: Readonly<Record<string, LifeEventPassage>> = BIRTHDAY_BY_DATE): boolean =>
  allBirthdayDates().every((date) => Object.prototype.hasOwnProperty.call(record, date));
