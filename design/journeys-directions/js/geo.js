  // A closed Catmull-Rom curve through the points, as cubic Béziers: hand-traced corners become a soft coastline.
  function smooth(points, closed = true, tension = 0.5) {
    const p = points.map(project), n = p.length;
    if (n < 2) return "";
    const idx = (i) => (closed ? (i + n) % n : Math.max(0, Math.min(n - 1, i)));
    const at = (i) => p[idx(i)], far = (i) => points[idx(i)][2] === 1;
    let d = `M${p[0][0].toFixed(1)},${p[0][1].toFixed(1)}`;
    const last = closed ? n : n - 1;
    for (let i = 0; i < last; i++) {
      const p0 = at(i - 1), p1 = at(i), p2 = at(i + 1), p3 = at(i + 2), t = tension / 3;
      if (far(i) || far(i + 1)) { d += `L${p2[0].toFixed(1)},${p2[1].toFixed(1)}`; continue; }
      const c1 = [p1[0] + (p2[0] - p0[0]) * t, p1[1] + (p2[1] - p0[1]) * t];
      const c2 = [p2[0] - (p3[0] - p1[0]) * t, p2[1] - (p3[1] - p1[1]) * t];
      d += `C${c1[0].toFixed(1)},${c1[1].toFixed(1)} ${c2[0].toFixed(1)},${c2[1].toFixed(1)} ${p2[0].toFixed(1)},${p2[1].toFixed(1)}`;
    }
    return closed ? `${d}Z` : d;
  }
  function inside([lon, lat], poly) {
    let hit = false;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [xi, yi] = poly[i], [xj, yj] = poly[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
    }
    return hit;
  }
