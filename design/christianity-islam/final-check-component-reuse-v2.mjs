import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import path from 'node:path';
const dir=path.dirname(fileURLToPath(import.meta.url));
const require=createRequire(path.resolve('package.json'));
const {chromium}=require('@playwright/test');
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
const errors=[],badResponses=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)badResponses.push({url:r.url(),status:r.status()})});
const root='http://127.0.0.1:8931/mockups/christianity-islam/';
await page.goto('http://localhost:8765/');
await page.waitForURL(root);
await page.locator('.concept-two-paths').waitFor();
if(await page.locator('.ap-navigation a[aria-current=page]').innerText()!=='Worldviews')throw Error('Worldviews current state missing');
for(const theme of ['dark','light']){
 if(await page.locator('html').getAttribute('data-theme')!==theme)await page.getByRole('switch',{name:'Dark mode'}).click();
 for(const width of [1440,390]){
  await page.setViewportSize({width,height:1000});
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:path.join(dir,'screenshots',`${theme}-hub-${width===1440?'desktop':'mobile'}.png`),fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Final hub overflow');
 }
 await page.setViewportSize({width:1440,height:900});
 await page.screenshot({path:path.resolve(dir,`../_gallery/thumbs/christianity-islam-${theme}.png`)});
}
await page.goto(root+'?view=world&country=PAK');
await page.locator('.mw-globe-stage').scrollIntoViewIfNeeded();
await page.locator('.mw-globe-stage[aria-busy=false]').waitFor();
await page.getByRole('button',{name:'Search countries',exact:true}).click();
await page.getByRole('searchbox',{name:'Find a country',exact:true}).fill('Egypt');
await page.getByRole('button',{name:'Egypt',exact:true}).click();
await page.getByRole('article',{name:'Egypt country profile',exact:true}).waitFor();
if(!page.url().includes('country=EGY')||!page.url().includes('view=world'))throw Error('Country selection lost route');
await page.getByRole('button',{name:/View Unengaged and unreached people groups/}).click();
if(await page.getByRole('tab',{name:/People Groups/}).getAttribute('aria-selected')!=='true')throw Error('Presence to groups transition failed');
if(!page.url().includes('engagement=unengaged'))throw Error('Engagement not shareable');
await page.reload();
await page.getByRole('article',{name:'Egypt country profile',exact:true}).waitFor();
if(await page.getByRole('tab',{name:/People Groups/}).getAttribute('aria-selected')!=='true')throw Error('Group tab not retained on refresh');
await page.getByRole('button',{name:'Flat map view',exact:true}).click();
await page.locator('.mw-globe-stage.is-flat[aria-busy=false]').waitFor();
await page.getByRole('button',{name:'Globe view',exact:true}).click();
await page.locator('.mw-globe-stage:not(.is-flat)[aria-busy=false]').waitFor();
await page.evaluate(()=>window.scrollTo(0,0));
await page.screenshot({path:path.join(dir,'screenshots','atlas-groups-final.png'),fullPage:true});
await page.goto(root+'?view=questions');
await page.locator('.wv-claim-map').waitFor();
const previous=await page.evaluate(()=>localStorage.getItem('bp-apologetics-notebook-v1'));
await page.getByRole('button',{name:'Write a reflection',exact:true}).click();
await page.locator('textarea').fill('Preview-only reflection for verification.');
if(await page.evaluate(()=>localStorage.getItem('bp-apologetics-notebook-v1'))!==previous)throw Error('Mockup changed real notes');
if(!await page.evaluate(()=>localStorage.getItem('bp-islam-design-notebook-v1')?.includes('Preview-only')))throw Error('Preview note not saved');
await page.goto(root+'?view=library');
await page.getByRole('button',{name:'Connected studies',exact:true}).click();
if(await page.locator('.wv-study-card').count()!==7)throw Error('Study filter failed');
await page.getByRole('button',{name:'Proposed articles',exact:true}).click();
await page.getByRole('link',{name:/Journeys toward Christian faith/}).click();
if(await page.locator('.concept-article-header h1').innerText()!=='Journeys toward Christian faith')throw Error('Article library route failed');
await page.goto(root+'?view=worldviews');
await page.locator('.wv-collection').filter({hasText:'Christianity & Islam'}).click();
await page.locator('.concept-two-paths').waitFor();
await page.goto('http://127.0.0.1:8931/apologetics/worldviews/islam');
await page.locator('#muslim-world').scrollIntoViewIfNeeded();
await page.locator('.mw-globe-stage[aria-busy=false]').waitFor();
await page.screenshot({path:path.join(dir,'current-world.png')});
await browser.close();
fs.writeFileSync(path.join(dir,'final-verification.json'),JSON.stringify({legacyLocalhostRedirect:'passed',selfContainedStylesAndFonts:'passed',currentNavigation:'passed',countrySearch:'passed',presenceToPeopleGroups:'passed',sharedFilterRefresh:'passed',globeAndFlatMap:'passed',previewNotebookIsolation:'passed',libraryFilters:'passed',worldviewsToHub:'passed',errors,badResponses},null,2));
if(errors.length||badResponses.length)throw Error(JSON.stringify({errors,badResponses}));
console.log('Final local asset, navigation, atlas and storage checks passed.');
