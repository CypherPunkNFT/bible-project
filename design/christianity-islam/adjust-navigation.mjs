import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const dir=path.dirname(fileURLToPath(import.meta.url));
const file=path.join(dir,'preview.tsx');
let s=fs.readFileSync(file,'utf8');
const start=s.indexOf('<nav className="ap-navigation"');
const end=s.indexOf('<div className="wv-page concept-content"',start);
if(start<0||end<0)throw Error('Navigation region not found');
const topEnd=s.indexOf('</nav>',start)+6;
const top=s.slice(start,topEnd);
const bottomStart=s.indexOf('<nav className="concept-local-nav"',topEnd);
const bottomEnd=s.indexOf('</nav>',bottomStart)+6;
const bottom=s.slice(bottomStart,bottomEnd);
s=s.slice(0,start)+'<div className="concept-nav-container">'+top+"{view!=='worldviews'&&"+bottom+'}</div>'+s.slice(end);
const back='<Go view="worldviews" className="concept-title-back"><ArrowLeft size={13}/>All worldviews</Go>';
s=s.replace('<div><Eyebrow>{eyebrow}</Eyebrow><h1','<div>'+back+'<Eyebrow>{eyebrow}</Eyebrow><h1');
s=s.replace('<div className="concept-article-header"><Eyebrow>','<div className="concept-article-header">'+back+'<Eyebrow>');
fs.writeFileSync(file,s);
console.log('Grouped navigation rows; replaced breadcrumb with title-level back link.');
